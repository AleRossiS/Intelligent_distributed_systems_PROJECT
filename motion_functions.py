import numpy as np
from scipy.stats import levy_stable
import matplotlib.pyplot as plt
from shapely.geometry import Point, LineString
import config as cfg


## HYPERPARAMETERS ##

## Lévy Flight parameters ##
MAX_TIME = 10       # Maximum time to keep moving in the same direction
MIN_TIME = 4        # Minimum time to keep moving in the same direction
LIN_VEL = 1.0       # Linear velocity magnitude
ANG_VEL_GAIN = 1  # Angular velocity gain for turning
ALPHA = 1.5         # Lévy distribution parameter (0 < alpha <= 2)
BETA = 1.0          # Lévy distribution skewness parameter (-1 <= beta <= 1)
SCALE = 1.0         # Lévy distribution scale parameter (scale > 0

## Obstacle avoidance parameters ##
D_MIN = cfg.ROBOT_RADIUS * 2  # Minimum distance to start avoiding obstacles
REPULSIVE_GAIN = 5 # Repulsive control gain

        
        

class MotionController:
    """
    External controller that generates the control inputs for the robots [v, w].
    
    This class implements:
        - A Lévy Flight-based control strategy for exploration and treasure hunt.
        -
        -
    """
    def __init__(self):
        ## Lévy Distribution parameters ##

        # Internal navigation state
        self.time_remaining = 0.0
        self.target_theta = 0.0
        self.levy_theta = 0.0
        self.avoidance_dir = None # direction in whitch to rotate when near boundary (1 for CCW, -1 for CW)

    def levy_control(self, robot_state, dt, voronoi):
        """
        Calculates the [v, w] commands based on Levy Flight using the current robot state.
        If the robot is too close to its Voronoi boundary a repulsive control is computed and summed 
        with the one generated by the Levy Flight control.
        
        Args:
            robot_state: The numpy array [x, y, theta] representing the robot's state
            dt: Time step
            voronoi: the voronoi cell of the control robot 
            
        Returns:
            A numpy array containing the linear and angular velocities controls [v, w] 
        """

        x, y, theta = robot_state # Current orientation of the robot
        robot_pos = Point(x, y) # Current position as a Point object
        
        # 1. Create a line in the direction of the robot's heading and check distance to Voronoi boundary
        heading_line = LineString([(x, y), (x + cfg.SENSING_RANGE*1.2 * np.cos(theta), y + cfg.SENSING_RANGE*1.2 * np.sin(theta))])

        is_near_boundary = False # Initialize the flag
        
        # Find the intersection point between the Voronoi and the heading line 
        if voronoi.exterior.intersects(heading_line):
            intersection = voronoi.exterior.intersection(heading_line) 
            
        # Compute distance to the boundary
        if not intersection.is_empty:
            if intersection.geom_type == 'Point':
                dist = robot_pos.distance(intersection)
                
            # Check if the robot is within a certain threshold distance to the boundary
            if dist < cfg.SENSING_RANGE * 0.5:
                is_near_boundary = True
            
        # 2. If near the boundary, rotate untill the obstacle is not in sight
        if is_near_boundary:
            
            if self.avoidance_dir is None:
                # Decide randomly whether to turn clockwise or counterclockwise
                self.avoidance_dir = np.random.choice([-1, 1])
             
            self.levy_theta = theta + np.pi/8*(self.avoidance_dir) # Increment the angle 
            
            # Sample from Lévy distribution new time (to be used when the robot will be able to move forward again)
            raw_time = levy_stable.rvs(alpha=ALPHA,    # stability parameter (0 < alpha <= 2)
                                       beta=BETA,      # skewness parameter (-1 <= beta <= 1)
                                       loc=MIN_TIME,   # location parameter
                                       scale=SCALE)    # scale parameter (scale > 0)
            
            self.time_remaining = np.clip(abs(raw_time), MIN_TIME, MAX_TIME)  # Ensure time is within bounds
        else:
            self.avoidance_dir = None # Reset the boundary avoidance direction when not near boundary anymore
        
        # 3. If no obtscle in the line of sight do Levy Control + Obstacles repulsion 
            if self.time_remaining <= 0:
                self.levy_theta = np.random.uniform(-np.pi, np.pi) # Random new direction
                
                #Sample from Levy dsitrib
                raw_time = levy_stable.rvs(alpha=ALPHA,  # stability parameter (0 < alpha <= 2)
                                        beta=BETA,     # skewness parameter (-1 <= beta <= 1)
                                        loc=MIN_TIME, # location parameter
                                        scale=SCALE)    # scale parameter (scale > 0)
                
                self.time_remaining = np.clip(abs(raw_time), MIN_TIME, MAX_TIME)  # Ensure time is within bounds
                
        # Obscale avoidance repulsive control and Levy Flight direction velocity vector
        v_rep = self.obstacle_avoidance_control(robot_state, voronoi) # repulsive vector 
        v_levy = np.array([np.cos(self.levy_theta), np.sin(self.levy_theta)]) # Levy vector 
    
        # New target angle based on the combination of repulsive and Levy vectors
        self.target_theta = np.arctan2(v_rep[1] + v_levy[1], v_rep[0] + v_levy[0]) 
                
        # 5. Angular error calculation
        angle_error = self.target_theta - theta
        angle_error = (angle_error + np.pi) % (2 * np.pi) - np.pi # Normalize to [-pi, pi]

        # Angoular velocity proportional to the error
        w = ANG_VEL_GAIN * angle_error 
        
        # If the angloular error is big rotate in place otherwise performs smooth curves 
        if abs(angle_error) > (np.pi / 4.0): 
            v = 0.0
        else:
            v = LIN_VEL * np.cos(angle_error)
            
        self.time_remaining -= dt # decrease time remaining 

        return np.array([v, w])
    
    def obstacle_avoidance_control(self, robot_state, voronoi):
        """
        Calculates a quadratic repulsive force vector to steer the robot away from obstacles.
        The force activates only when the robot is closer to the boundary of its Voronoi than the `D_MIN` threshold. 
        
        Args:
            robot_state: A numpy array or list containing the robot's current [x, y, theta].
            voronoi: A Shapely Polygon representing the robot's assigned Voronoi cell.
            
        Returns:
            A 2D numpy array [F_x, F_y] representing the repulsive force vector. 
            Returns [0.0, 0.0] if the robot is at a safe distance.
        """
        
        x, y, theta = robot_state
        robot_pos = Point(x, y)
        
        # Find the closest point on the Voronoi boundary to the robot
        closest_point_coords = voronoi.exterior.interpolate(voronoi.exterior.project(robot_pos))
        closest_point = Point(closest_point_coords)
        
        # Compute the distance to the closest point on the boundary
        dist = robot_pos.distance(closest_point)
        
        repulsive_force = np.array([0.0, 0.0])
        
        if dist < D_MIN:
            dir = np.array([x - closest_point.x, y - closest_point.y]) # Direction away from the boundary
            if np.linalg.norm(dir) > 0:
                dir = dir / np.linalg.norm(dir) # Normalize the direction
                
                # Quadratic repulsive conrtol 
                repulsive_force = REPULSIVE_GAIN * ((D_MIN - dist) ** 2) * dir

        return repulsive_force


    def plot_levy_distribution(self, num_samples=10000):
        """
        Plots the Lévy distribution for visualization and debugging purposes.
        """
        
        x = np.linspace(0, 15, num_samples)
        pdf = levy_stable.pdf(x, alpha=ALPHA, beta=BETA, loc=MIN_TIME, scale=SCALE)

        plt.ioff() 
        
        fig = plt.figure(figsize=(8, 5))
        plt.plot(x, pdf, color='blue', linewidth=2)
        
        plt.axvline(x=MIN_TIME, color='red', linestyle='--', linewidth=2, label=f'MIN_TIME ({MIN_TIME})')
        plt.axvline(x=MAX_TIME, color='green', linestyle='--', linewidth=2, label=f'MAX_TIME ({MAX_TIME})')
        
        plt.title("Levy Distribution PDF (alpha={}, beta={})".format(ALPHA, BETA))
        plt.xlabel("Time Duration")
        plt.ylabel("Probability Density")
        plt.grid(True)
        
        plt.legend()
        plt.show()
        

            