## HYPERPARAMETERS ##

## Lévy Flight parameters ##
MAX_TIME_EXPLOR = 10       # Maximum time to keep moving in the same direction during exploration
MIN_TIME_EXPLOR = 4        # Minimum time to keep moving in the same direction during exploration
MAX_TIME_TREAS = 4       # Maximum time to keep moving in the same direction when treasure is found
MIN_TIME_TREAS = 2        # Minimum time to keep moving in the same direction when treasure is found
LIN_VEL = 2.0       # Linear velocity magnitude
ANG_VEL_GAIN = 1  # Angular velocity gain for turning
ALPHA = 1.5         # Lévy distribution parameter (0 < alpha <= 2)
BETA = 1.0          # Lévy distribution skewness parameter (-1 <= beta <= 1)
SCALE = 1.0         # Lévy distribution scale parameter (scale > 0)

## Obstacle avoidance parameters ##
D_MIN = cfg.ROBOT_RADIUS * 2  # Minimum distance to start avoiding obstacles
REPULSIVE_GAIN_FOR_LEVY = 8 # Repulsive control gain for obstacle avoidance during Levy flight 
REPULSIVE_GAIN_FOR_LOYD = 0.5 # Repulsive control gain for obstacle avoidance during Lloyd's algorithm


        
        

class MotionController:
    """
    External controller that generates the control inputs for the robots [v, w].
    
    This class implements:
        - A Lévy Flight-based control strategy for exploration and treasure hunt.
        -
        -
    """
    def __init__(self):
        ## Lévy Distribution parameters ##

        # Internal navigation state
        self.time_remaining = 0.0
        self.target_theta = 0.0
        self.levy_theta = 0.0
        self.avoidance_dir = None # direction in whitch to rotate when near boundary (1 for CCW, -1 for CW)

    def levy_control(self, robot_state, dt, voronoi, min_time, max_time):
        """
        Calculates the [v, w] commands based on Levy Flight using the current robot state.
        If the robot is too close to its Voronoi boundary a repulsive control is computed and summed 
        with the one generated by the Levy Flight control.
        
        Args:
            robot_state: The numpy array [x, y, theta] representing the robot's state
            dt: Time step
            voronoi: the voronoi cell of the control robot 
            min_time: Minimum time to keep moving in the same direction (Lévy flight parameter)
            max_time: Maximum time to keep moving in the same direction (Lévy flight parameter)
            
        Returns:
            A numpy array containing the linear and angular velocities controls [v, w] 
        """

        x, y, theta = robot_state # Current orientation of the robot
        robot_pos = Point(x, y) # Current position as a Point object
        
        # 1. Create a line in the direction of the robot's heading and check distance to Voronoi boundary
        heading_line = LineString([(x, y), (x + cfg.SENSING_RANGE*1.2 * np.cos(theta), y + cfg.SENSING_RANGE*1.2 * np.sin(theta))])

        is_near_boundary = False # Initialize the flag
        
        # Find the intersection point between the Voronoi and the heading line 
        if voronoi.exterior.intersects(heading_line):
            intersection = voronoi.exterior.intersection(heading_line) 
            
        # Compute distance to the boundary
        if not intersection.is_empty:
            if intersection.geom_type == 'Point':
                dist = robot_pos.distance(intersection)
                
            # Check if the robot is within a certain threshold distance to the boundary
            if dist < cfg.SENSING_RANGE * 0.5:
                is_near_boundary = True
            
        # 2. If near the boundary, rotate untill the obstacle is not in sight
        if is_near_boundary:
            
            if self.avoidance_dir is None:
                # Decide randomly whether to turn clockwise or counterclockwise
                self.avoidance_dir = np.random.choice([-1, 1])
             
            self.levy_theta = theta + np.pi/8*(self.avoidance_dir) # Increment the angle 
            
            # Sample from Lévy distribution new time (to be used when the robot will be able to move forward again)
            raw_time = levy_stable.rvs(alpha=ALPHA,    # stability parameter (0 < alpha <= 2)
                                       beta=BETA,      # skewness parameter (-1 <= beta <= 1)
                                       loc=min_time,   # location parameter
                                       scale=SCALE)    # scale parameter (scale > 0)
            
            self.time_remaining = np.clip(abs(raw_time), min_time, max_time)  # Ensure time is within bounds
        else:
            self.avoidance_dir = None # Reset the boundary avoidance direction when not near boundary anymore
        
        # 3. If no obtscle in the line of sight do Levy Control + Obstacles repulsion 
        if self.time_remaining <= 0:
            self.levy_theta = np.random.uniform(-np.pi, np.pi) # Random new direction
            
            #Sample from Levy dsitribution
            raw_time = levy_stable.rvs(alpha=ALPHA,  # stability parameter (0 < alpha <= 2)
                                    beta=BETA,     # skewness parameter (-1 <= beta <= 1)
                                    loc=min_time, # location parameter
                                    scale=SCALE)    # scale parameter (scale > 0)
            
            self.time_remaining = np.clip(abs(raw_time), min_time, max_time)  # Ensure time is within bounds
            
        # Obscale avoidance repulsive control and Levy Flight direction velocity vector
        v_rep = self.obstacle_avoidance_control(robot_state, voronoi) # repulsive vector 
        v_levy = np.array([np.cos(self.levy_theta), np.sin(self.levy_theta)]) # Levy vector 
    
        # New target angle based on the combination of repulsive and Levy vectors
        self.target_theta = np.arctan2(v_rep[1] + v_levy[1], v_rep[0] + v_levy[0]) 
                
        # 5. Angular error calculation
        angle_error = self.target_theta - theta
        angle_error = (angle_error + np.pi) % (2 * np.pi) - np.pi # Normalize to [-pi, pi]

        # Angoular velocity proportional to the error
        w = ANG_VEL_GAIN * angle_error 
        
        # If the angloular error is big rotate in place otherwise performs smooth curves 
        if abs(angle_error) > (np.pi / 4.0): 
            v = 0.0
        else:
            v = LIN_VEL * max(0.0, np.cos(angle_error)**3) # Modulate linear velocity 
            
        self.time_remaining -= dt # decrease time remaining 

        return np.array([v, w])
    
    
    def obstacle_avoidance_control(self, robot_state, voronoi):
        """
        Calculates a quadratic repulsive force vector to steer the robot away from obstacles.
        The force activates only when the robot is closer to the boundary of its Voronoi than the `D_MIN` threshold.
        
        This method is then used inside the `levy_control` method to combine the exploration behavior with obstacle avoidance. 
        
        Args:
            robot_state: A numpy array or list containing the robot's current [x, y, theta].
            voronoi: A Shapely Polygon representing the robot's assigned Voronoi cell.
            
        Returns:
            A 2D numpy array [F_x, F_y] representing the repulsive force vector. 
            Returns [0.0, 0.0] if the robot is at a safe distance.
        """
        
        x, y, theta = robot_state
        robot_pos = Point(x, y)
        
        # Find the closest point on the Voronoi boundary to the robot
        closest_point_coords = voronoi.exterior.interpolate(voronoi.exterior.project(robot_pos))
        closest_point = Point(closest_point_coords)
        
        # Compute the distance to the closest point on the boundary
        dist = robot_pos.distance(closest_point)
        
        repulsive_force = np.array([0.0, 0.0])
        
        if dist < D_MIN:
            dir = np.array([x - closest_point.x, y - closest_point.y]) # Direction away from the boundary
            if np.linalg.norm(dir) > 0:
                dir = dir / np.linalg.norm(dir) # Normalize the direction
                
                # Quadratic repulsive conrtol 
                repulsive_force = REPULSIVE_GAIN_FOR_LEVY * ((D_MIN - dist) ** 2) * dir

        return repulsive_force


    def plot_levy_distribution(self, num_samples=10000):
        """
        Plots the Lévy distribution for visualization and debugging purposes (Utility).
        """
        
        x = np.linspace(0, 15, num_samples)
        pdf = levy_stable.pdf(x, alpha=ALPHA, beta=BETA, loc=MIN_TIME_EXPLOR, scale=SCALE)

        plt.ioff() 
        
        fig = plt.figure(figsize=(8, 5))
        plt.plot(x, pdf, color='blue', linewidth=2)
        
        plt.axvline(x=MIN_TIME_EXPLOR, color='red', linestyle='--', linewidth=2, label=f'MIN_TIME ({MIN_TIME_EXPLOR})')
        plt.axvline(x=MAX_TIME_EXPLOR, color='green', linestyle='--', linewidth=2, label=f'MAX_TIME ({MAX_TIME_EXPLOR})')
        
        plt.title("Levy Distribution PDF (alpha={}, beta={})".format(ALPHA, BETA))
        plt.xlabel("Time Duration")
        plt.ylabel("Probability Density")
        plt.grid(True)
        
        plt.legend()
        plt.show()


    def wall_following_control(self, robot_state, closest_point):
        """
        Control strategy for sliding along obstacles when in INSPECTING state.
        
        Args:
            robot_state: A numpy array or list containing the robot's current [x, y, theta].
            closest_point: A Shapely Point representing the closest point on the Voronoi boundary.
            
        Returns:
            A numpy array [v, w] representing the linear and angular velocity commands for wall-following behavior.
        """
        
        x, y, theta = robot_state
        dx = closest_point.x - x
        dy = closest_point.y - y
        dist = np.hypot(dx, dy)
        
        # Target distance to maintain from the wall
        d_target = cfg.ROBOT_RADIUS * 1.5
        
        # 1. Compute normal vector (robot to obstacle)
        if dist == 0: dist = 0.001 # Prevent division by zero
        nx, ny = dx / dist, dy / dist
        
        # 2. Compute tangent vector for sliding (CW direction)
        # Note: Use (-ny, nx) for CCW direction
        tx, ty = ny, -nx 
        
        # 3. P-controller for distance correction
        error = dist - d_target
        K_p = 3.0 # Proportional gain
        
        # 4. Combine tangent flow and normal correction
        des_x = tx + K_p * error * nx
        des_y = ty + K_p * error * ny
        
        # 5. Compute heading error and normalize to [-pi, pi]
        target_theta = np.arctan2(des_y, des_x)
        angle_error = target_theta - theta
        angle_error = (angle_error + np.pi) % (2 * np.pi) - np.pi
        
        # 6. Compute velocity commands
        w = ANG_VEL_GAIN * angle_error
        
        # Modulate linear velocity based on the angle error to allow smooth sliding along the wall
        v = LIN_VEL * max(0.0, np.cos(angle_error)**3) # The **3 allows good control even with bigger angle errors
        return np.array([v, w])
    
    
    def formation_loyd_control(self, robot_state, goal_pos, voronoi, ring_radius=0.0):
        """
        Guides the robot towards the goal using a Lloyd-based control algorithm.
        If ring_radius > 0, uses a ring-shaped Gaussian PDF to form a circular formation, if = 0, uses a standard
        Gaussian PDF that guides the robot to the goal position.
        Also integrates obstacle avoidance by combining the Lloyd control vector with the repulsive 
        vector when near obstacles to better navigate around them.
        
        Args:
            robot_state: A numpy array or list containing the robot's current [x, y, theta].
            goal_pos: A tuple (goal_x, goal_y) representing the target position to reach.
            voronoi: A Shapely Polygon representing the robot's assigned Voronoi cell.
            ring_radius: If > 0, the radius of the ring-shaped PDF for circular formation control. 
            If = 0, standard Gaussian is used.
            
        Returns:
            A numpy array [v, w] representing the linear and angular velocity commands for formation control.
        """
        
        x, y, theta = robot_state
        goal_x, goal_y = goal_pos[0], goal_pos[1]
        
        # 1. Voronoi cell discretization
        minx, miny, maxx, maxy = voronoi.bounds
        grid_res = 15j 
        grid_x, grid_y = np.mgrid[minx:maxx:grid_res, miny:maxy:grid_res]
        points = np.vstack((grid_x.flatten(), grid_y.flatten())).T 
        
        # 2. Keep the points of the grid defined above that are inside the Voronoi cell
        poly_path = Path(list(voronoi.exterior.coords))
        inside_mask = poly_path.contains_points(points)
        valid_points = points[inside_mask]
        
        dist_to_goal = np.hypot(goal_x - x, goal_y - y) 
        
        # Fallback
        if len(valid_points) == 0:
            cx, cy = voronoi.centroid.x, voronoi.centroid.y
            
        else:
            # 3. Adaptive sigma calculation
            sigma_0 = 0.5 
            R_ad = 5.0        
            sigma_adaptive = sigma_0 * (1.0 + (dist_to_goal / R_ad))
            
            # 4. Weight calculation 
            dists_to_goal_grid = np.hypot(valid_points[:, 0] - goal_x, valid_points[:, 1] - goal_y)
            
            if ring_radius > 0.0:
                # Ring PDF
                weights = np.exp(-(dists_to_goal_grid - ring_radius)**2 / (2 * sigma_adaptive**2))
            else:
                # Gaussian PDF
                weights = np.exp(-(dists_to_goal_grid)**2 / (2 * sigma_adaptive**2))
            
            # 5. Weighted Centroid calculation
            weight_sum = np.sum(weights)
            if weight_sum > 0:
                cx = np.sum(valid_points[:, 0] * weights) / weight_sum
                cy = np.sum(valid_points[:, 1] * weights) / weight_sum
            else:
                cx, cy = voronoi.centroid.x, voronoi.centroid.y 
          
        # Compute distance to the centroid       
        dist_to_centroid = np.hypot(cx - x, cy - y)
        
        # If near the centroid stop, to avoid oscillations 
        if dist_to_centroid < 0.05:
            return np.array([0.0, 0.0])
                
        # Obstacle avoidance repulsive control
        # 1. Compute repulsive vector
        v_rep = self.obstacle_avoidance_control(robot_state, voronoi)
        
        # 2. Compute attractive vector towards the weighted centroid 
        v_attr = np.array([cx - x, cy - y])
        
        # 3. Rresultant vector combining attraction to the centroid and repulsion from obstacles
        final_vector = v_attr +  REPULSIVE_GAIN_FOR_LOYD * v_rep
        
        # 4. Unicycle commands [v, w] based on the final vector
        target_theta = np.arctan2(final_vector[1], final_vector[0])
        angle_error = (target_theta - theta + np.pi) % (2 * np.pi) - np.pi
        
        w = ANG_VEL_GAIN * angle_error
        v = LIN_VEL * max(0.0, np.cos(angle_error)**3) 
            
        return np.array([v, w])
    
    
    def lidar_mapping(self, robot, collision_map):
        """
        Simulates a 360-degree LiDAR sensor using ray-casting to detect obstacles and update the robot's internal map.
        The method casts rays in all directions, checks for intersections with the obstacles, and updates the robot's
        internal map with the detected points.
        
        Args:
            robot: The Robot object for which to perform LiDAR mapping.
            collision_map: A Shapely Polygon representing the collision map.
        
        Returns:
            A numpy array of shape (N, 2) containing the coordinates of the detected obstacle points.
        """
        
        robot_pos_arr = np.array([robot.state[0], robot.state[1]])
        robot_pos_pt = Point(robot_pos_arr)
        visible_hit_points = []
    
            
        # Ray casting
        if not collision_map.is_empty:
            num_rays = int(360 / cfg.RAY_CASTING_RESOLUTION)
            angles = np.linspace(0, 2 * np.pi, num_rays, endpoint=False)
            
            for angle in angles:
                # Create a single LiDAR ray up to SENSING_RANGE
                ray_end = (robot_pos_arr[0] + np.cos(angle) * cfg.SENSING_RANGE, 
                           robot_pos_arr[1] + np.sin(angle) * cfg.SENSING_RANGE)
                ray_line = LineString([robot_pos_arr, ray_end])
                
                # Check if the ray hits an obstacle
                if ray_line.intersects(collision_map):
                    
                    # Intersect with the BOUNDARY of the obstacles to get the exact hit point
                    hit_geom = ray_line.intersection(collision_map.boundary)
                    
                    hit_point = None
                    if hit_geom.geom_type == 'Point':
                        hit_point = hit_geom
                    elif hit_geom.geom_type in ['MultiPoint', 'GeometryCollection']:
                        # If the ray pierces multiple walls, get the closest hit point
                        # NOTE: Use .geoms to iterate over the geometry collection
                        hit_points_list = [pt for pt in hit_geom.geoms if pt.geom_type == 'Point']
                        if hit_points_list:
                            hit_point = min(hit_points_list, key=lambda pt: robot_pos_pt.distance(pt))
                        
                    # If we found a valid hit point on the wall
                    if hit_point is not None:
                        coord = (hit_point.x, hit_point.y)
                        visible_hit_points.append(coord)
                        
        return np.array(visible_hit_points) if len(visible_hit_points) > 0 else np.array([])
    

    def get_control(self, robot, all_robots, dt, voronoi, obstacles_map=Polygon(), inflated_map = Polygon(), target_obj=None):
        """
        Main interface for the Finite State Machine (FSM).
        Selects the appropriate control strategy and calculates [v, w] commands.
        
        Args:
            robot: The Robot object for which to calculate the control.
            all_robots: List of all Robot objects in the environment (used for shared map and communication).
            dt: Time step for control update.
            voronoi: The Voronoi cell (Shapely Polygon) of the robot.
            obstacles_map: A Shapely Polygon representing the collision map.
            inflated_map: A Shapely Polygon representing the inflated obstacle map.
            target_obj: The target object (Shapely Polygon) to be detected and measured by the robot.n 
            
        Returns:
            A numpy array [v, w] representing the linear and angular velocity commands for the robot.
        """
        
        # -- Obstacles sensing and Mapping #
        visible_hit_points = self.lidar_mapping(robot, inflated_map) # Get the visible hit points from the LiDAR mapping   
        
        # Extract current position
        robot_pos_arr = np.array([robot.state[0], robot.state[1]])
        
        
        # 2. Find the closest point for wall-following control
        if len(visible_hit_points) > 0:
            distances_to_real_obs = np.linalg.norm(visible_hit_points - robot_pos_arr, axis=1) # All distances
            min_idx = np.argmin(distances_to_real_obs) # Find the minimum distance index
            
            target_arr = visible_hit_points[min_idx] # The closest point
            closest_point = Point(target_arr[0], target_arr[1])
            dist_to_boundary = distances_to_real_obs[min_idx] # Distance to the closest point
        else:
            dist_to_boundary = float('inf') # Fallback if no obstacles are visible
            closest_point = None
            target_arr = None 
            
        
        LIDAR_HIT_THRESHOLD = cfg.SENSING_RANGE * 0.9
    
        ## ---------------- FINITE STATE MACHINE (FSM) ---------------- ##
        
        # --- TREASURE DETECTION  --- #
        if target_obj is not None and robot.state_mode in ["SEARCHING", "INSPECTING"]:
            
            # Use the robot's internal sensor to detect and measure the target
            if robot.measure_target_edge(target_obj, obstacles_map):
                return np.array([0.0, 0.0]) # Stop to stabilize after finding the target
                
                    
        # --- 1. SEARCHING STATE ---
        if robot.state_mode == "SEARCHING":
            
            # Check if a real obstacle is hit to start mapping
            if dist_to_boundary < LIDAR_HIT_THRESHOLD and target_arr is not None:
                
                is_already_inspected = False # Flag initialization
                
                # If the point is already inspected, we don't want to switch to INSPECTING state again 
                for pt in robot.shared_map:
                    if np.linalg.norm(target_arr - pt) < cfg.MAP_RESOLUTION:
                        is_already_inspected = True
                        break 
                
                # If new real obstacle point and not already inspected, switch to INSPECTING state to start mapping it
                if not is_already_inspected:
                    robot.state_mode = "INSPECTING"
                    
                    for pt in visible_hit_points:
                        is_duplicate = False
                        
                        # Check if the new point is too close to already inspected points to avoid too colse points
                        for saved_pt in robot.inspected_points[-30:]:  # Only check most recent 30 points (mem saving)
                            if np.linalg.norm(pt - saved_pt) < cfg.MAP_RESOLUTION:
                                is_duplicate = True
                                break
                        
                        # If the point is not a duplicate add to the inspected points and update the shared map        
                        if not is_duplicate:
                            robot.inspected_points.append(pt) 
                            robot.update_shared_map([pt])
                            
                    return np.array([0.0, 0.0]) # Stop to stabilizee

            # Default: Levy flight exploration, if no new real obstacles are detected in the line of sight
            return self.levy_control(robot.state, dt, voronoi, min_time=MIN_TIME_EXPLOR, max_time=MAX_TIME_EXPLOR)
                
                
        # --- 2. INSPECTING STATE (Mapping Mode) --- 
        elif robot.state_mode == "INSPECTING":
            
            # Store new visible obstacle points
            if len(visible_hit_points) > 0:
                for new_pt in visible_hit_points:
                    is_duplicate = False
                    
                    # Check if the new point is too close to already inspected points to avoid duplicates in the memory
                    for saved_pt in robot.inspected_points[-30:]: # Only check the most recent 30 points to save time
                        if np.linalg.norm(new_pt - saved_pt) < cfg.MAP_RESOLUTION:
                            is_duplicate = True
                            break
                            
                    if not is_duplicate:
                        # If the point is not a duplicate, add it to the inspected points and update the shared map
                        robot.inspected_points.append(new_pt)
                        robot.update_shared_map([new_pt])
            
            # Check for loop closure
            loop_closed = False
            IGNORE_RADIUS_LOOP = cfg.ROBOT_RADIUS * 1.5 
            safe_history_index = len(robot.shared_map) - 50 # Only check for loop closure with points that are at least 50 steps old to avoid false positives with current mapping area
            
            if safe_history_index > 0 and target_arr is not None:
                for pt in robot.shared_map[:safe_history_index]:
                    if np.linalg.norm(target_arr - pt) < IGNORE_RADIUS_LOOP:
                        loop_closed = True # Set flag to true if the robot is mapping an already well mapped area
                        break 

            # Robot collision avoidance with other robots
            too_close_to_friend = False
            CRITICAL_DISTANCE = cfg.ROBOT_RADIUS * 3.5 
            
            for other_pos in robot.other_robots_positions.values():
                if np.linalg.norm(robot_pos_arr - np.array(other_pos)) < CRITICAL_DISTANCE:
                    too_close_to_friend = True
                    break

            # State transition based on mapping progress or collision risk
            if loop_closed or too_close_to_friend:
                robot.state_mode = "SEARCHING"
                self.levy_theta = robot.state[2] + np.pi # Turn 180 deg
                self.time_remaining = MAX_TIME_EXPLOR 
                return np.array([0.0, 0.0])
                
            else:
                # If still in INSPECTING state, do wall-following control to slide along the obstacle and map it 
                if closest_point is not None:
                    return self.wall_following_control(robot.state, closest_point)
                else:
                    # Lost track of the wall
                    robot.state_mode = "SEARCHING"
                    return np.array([0.0, 0.0])
                
                            
        # --- 3. TREASURE FOUND STATE ---
        elif robot.state_mode in "TREASURE_FOUND":
            
            if getattr(robot, 'is_finder', False) and not getattr(robot, 'has_called_help', False):
                
                # If the robot is the finder and has not called for help yet, broadcast a call to join the formation
                robot.broadcast_help(all_robots)
                robot.has_called_help = True # Ensure the call for help is only sent once
            
            # Both the finder and the joining robots use the ring-based Lloyd control continuously.
            return self.formation_loyd_control(robot.state, robot.target_treasure_pos, voronoi, ring_radius=cfg.RING_RADIUS)
            
        return np.array([0.0, 0.0]) # Safety Fallback